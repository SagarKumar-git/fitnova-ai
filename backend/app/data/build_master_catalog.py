def build():
    from app.data.generate_catalog import CATALOG_ITEMS
    from app.data.expand_catalog import ADDITIONAL_ITEMS

    all_raw = CATALOG_ITEMS + ADDITIONAL_ITEMS + EXTRA_ITEMS
    print(f"Total raw items across all lists: {len(all_raw)}")

    # Deduplicate strictly by normalized name
    seen = {}
    master_catalog = []

    for item in all_raw:
        norm_name = re.sub(r"[^a-z0-9]", "", item["name"].lower())
        if norm_name in seen:
            print(f"Duplicate found and skipped: {item['name']} (matches {seen[norm_name]['name']})")
            continue
        seen[norm_name] = item
        master_catalog.append(item)

    print(f"Master Catalog verified unique items: {len(master_catalog)}")

    # Write out to food_catalog.json
    target_path = os.path.join(os.path.dirname(__file__), "food_catalog.json")
    with open(target_path, "w", encoding="utf-8") as f:
        json.dump(master_catalog, f, indent=2, ensure_ascii=False)

    print(f"Successfully saved to {target_path}")

    # Print summary statistics
    cuisines = set(x.get("cuisine", "Unknown") for x in master_catalog)
    categories = set(x.get("category", "Unknown") for x in master_catalog)
    veg_count = sum(1 for x in master_catalog if x.get("is_vegetarian"))
    vegan_count = sum(1 for x in master_catalog if x.get("is_vegan"))
    icmr_count = sum(1 for x in master_catalog if "ICMR" in str(x.get("source", "")))
    usda_count = sum(1 for x in master_catalog if "USDA" in str(x.get("source", "")))

    print("\n--- MASTER CATALOG SUMMARY ---")
    print(f"Total Items: {len(master_catalog)}")
    print(f"Distinct Cuisines ({len(cuisines)}): {sorted(list(cuisines))}")
    print(f"Distinct Categories ({len(categories)}): {sorted(list(categories))}")
    print(f"Vegetarian: {veg_count} | Vegan: {vegan_count}")
    print(f"Attribution Sources -> ICMR-IFCT: {icmr_count}, USDA-FoodData: {usda_count}")

if __name__ == "__main__":
    build()
